"""Writes evaluation_report.md and model_card.md from the metadata produced by train.py.
Every number in these files comes from the training run; nothing is typed in by hand."""
import os


def pct(x):
    return f"{100 * x:.2f}%"


def num(x, d=4):
    return f"{x:.{d}f}"


def cm_row(name, m):
    return (f"| {name} | {m['threshold']} | {num(m['precision'])} | {num(m['recall'])} | {m['tp']} | {m['fp']} | {m['fn']} | {m['tn']} | "
            f"{pct(m['flag_rate'])} |")


def banner(meta):
    if meta["synthetic_data"]:
        return ("> **SYNTHETIC DATA RUN.** These numbers come from the synthetic stand-in dataset in `devdata/`, not from the official\n"
                "> case-study file. They only prove that the pipeline runs end to end. Copy the official data pack into `data/` and run\n"
                "> `docker compose run --rm ml python train.py` (or `python ml/train.py`) to regenerate this report.\n\n")
    return ""


def evaluation_report(meta, examples):
    m = meta["metrics"]
    x, b, i = m["xgboost"], m["baseline"], m["isolation_forest"]
    ratio = x["pr_auc"] / b["pr_auc"] if b["pr_auc"] else float("nan")
    lines = [
        "# FraudShield model evaluation report", "",
        banner(meta) + f"Generated by `ml/train.py` on {meta['trained_at']} for model `{meta['model_version']}`.", "",
        "## Data and split", "",
        f"- Dataset: `{meta['dataset']}` ({meta['rows']['total']:,} rows)",
        f"- Out-of-time split: {meta['split']}; seed {meta['seed']}",
        f"- Train {meta['rows']['train']:,} rows (fit {meta['rows']['fit']:,} + validation {meta['rows']['validation']:,}, the latest 20% of the training period); "
        f"test {meta['rows']['test']:,} rows",
        f"- Fraud rate: train {pct(meta['fraud_rate']['train'])}, test {pct(meta['fraud_rate']['test'])}",
        "- Features: " + ", ".join(f"`{f}`" for f in meta["features"]) + ". Not used: `txn_id`, `txn_ts`, `city_tier`.",
        f"- Class imbalance: `scale_pos_weight` chosen on the validation slice: **{meta['scale_pos_weight']['chosen']}** "
        f"({meta['scale_pos_weight']['value']:.2f}); validation PR-AUC per option: "
        + ", ".join(f"{k} {v:.4f}" for k, v in meta["scale_pos_weight"]["validation_pr_auc"].items()),
        f"- Early stopping on validation PR-AUC: best iteration {meta['best_iteration']}", "",
        "## Test-period results (AI-1)", "",
        "| Detector | PR-AUC (primary) | ROC-AUC |", "|---|---|---|",
        f"| XGBoost | {num(x['pr_auc'])} | {num(x['roc_auc'])} |",
        f"| Rules-only baseline | {num(b['pr_auc'])} | {num(b['roc_auc'])} |",
        f"| Isolation Forest (AI-4, unsupervised) | {num(i['pr_auc'])} | {num(i['roc_auc'])} |", "",
        f"XGBoost PR-AUC is **{ratio:.2f}x** the baseline PR-AUC (reference target: at least 2x). "
        f"Isolation Forest ROC-AUC {'is above' if i['roc_auc'] > b['roc_auc'] else 'is not above'} the baseline ROC-AUC.", "",
        "### Precision, recall and confusion matrix", "",
        "| Detector / operating point | Threshold | Precision | Recall | TP | FP | FN | TN | Flag rate |", "|---|---|---|---|---|---|---|---|---|",
        cm_row("XGBoost at step-up threshold", x["at_step_up_threshold"]),
        cm_row("XGBoost at block threshold", x["at_block_threshold"]),
        cm_row("XGBoost at cost-optimal threshold", x["at_cost_threshold"]),
        cm_row("Baseline: any rule (score > 0)", b["flag_any_rule"]),
        cm_row("Baseline: score 100", b["score_100"]), "",
        "## Expected cost (AI-3)", "",
        "A missed fraud costs its transaction amount; a false alarm costs INR 150. The cost-optimal threshold was chosen on the validation "
        "slice and is reported here on the test period.", "",
        "| Operating point | Threshold | Missed fraud (INR) | False alarms | Total cost (INR) |", "|---|---|---|---|---|",
    ]
    for name, c in meta["costs"].items():
        lines.append(f"| {name} | {c['threshold']} | {c['missed_fraud_inr']:,.2f} | {c['false_alarms']:,} | {c['total_cost_inr']:,.2f} |")
    lines += ["", "## Friction on genuine transactions by segment (AI-3)", "",
              "Model friction = share of genuine test transactions with fraud_score >= 0.70 (the model would step up or block). "
              "System friction also counts transactions any baseline rule flags.", "",
              "| Dimension | Segment | Genuine txns | Model friction | Ratio (lowest / highest) | System friction | Ratio |", "|---|---|---|---|---|---|---|"]
    for s in meta["segments"]:
        lines.append(f"| {s['dimension']} | {s['segment']} | {s['genuine_txns']:,} | {pct(s['model_friction_rate'])} | {s['model_friction_rate_ratio']:.2f} | "
                     f"{pct(s['system_friction_rate'])} | {s['system_friction_rate_ratio']:.2f} |")
    lines.append("")
    if meta["disparities"]:
        lines += ["Segments where the lowest rate divided by the highest is below 0.8:", ""]
        for d in meta["disparities"]:
            lines.append(f"- **{d['dimension']} / {d['metric']}**: ratio {d['ratio']:.2f}, highest friction in `{d['highest']}`. "
                         "Largest feature differences for that segment: " + "; ".join(d["drivers"]) + ".")
        lines += ["", "See `ml/model_card.md` for the likely cause and mitigation.", ""]
    else:
        lines += ["All segment ratios are 0.8 or above.", ""]
    lat = meta["latency"]
    lines += ["## Inference latency", "",
              f"Single-row prediction plus SHAP contributions, in process, one thread: p50 {lat['p50_ms']:.2f} ms, p95 {lat['p95_ms']:.2f} ms "
              f"({lat['samples']} samples). The end-to-end authorisation latency is measured separately (`docs/TESTING.md`, category G).", "",
              "## Frauds missed by the rules baseline but caught by the model", "",
              f"{len(examples)} test-period frauds have baseline score 0 (the rules would approve) and fraud_score >= 0.70. Top examples:", "",
              "| txn_id | fraud_score | Top factors |", "|---|---|---|"]
    for e in examples[:5]:
        lines.append(f"| {e['txn_id']} | {e['fraud_score']:.4f} | " + "; ".join(f["text"] for f in e["top_factors"]) + " |")
    return "\n".join(lines) + "\n"


def model_card(meta):
    m = meta["metrics"]["xgboost"]
    lines = [
        "# Model card: FraudShield XGBoost fraud-risk model", "",
        banner(meta) + "_This file is regenerated by `ml/train.py`; edit `ml/report.py` to change its text._", "",
        "## Purpose", "",
        "Scores each card transaction with `fraud_score` (0 to 1) in the real-time authorisation path. The score only tightens the "
        "rules-engine decision: APPROVE becomes STEP_UP at 0.70 or more, STEP_UP becomes BLOCK at 0.90 or more (reason code "
        "`HIGH_FRAUD_SCORE_MODEL`). It never relaxes a rule decision. Confirming fraud and releasing false positives remain human decisions.", "",
        "## Model", "",
        f"- Version `{meta['model_version']}`, XGBoost gradient-boosted trees (max depth 4, learning rate 0.05, early stopping at "
        f"iteration {meta['best_iteration']}), seed {meta['seed']}.",
        f"- Class imbalance handled with `scale_pos_weight` = {meta['scale_pos_weight']['chosen']} (chosen on validation PR-AUC).",
        "- Explanations: exact TreeSHAP contributions from XGBoost (`pred_contribs`); the three largest positive contributions are "
        "shown to analysts in plain language.",
        "- Served by the Flask service in `ml/app.py`; the model is loaded once at start-up. The backend gives it 150 ms; slower or failed "
        "calls fall back to the rules-only decision with `model_status = MODEL_UNAVAILABLE`.", "",
        "## Data", "",
        f"- Training file `{meta['dataset']}`; out-of-time split ({meta['split']}).",
        f"- {meta['rows']['train']:,} training rows, {meta['rows']['test']:,} test rows; fraud rate {pct(meta['fraud_rate']['train'])} (train), "
        f"{pct(meta['fraud_rate']['test'])} (test).",
        "- Features (same definitions at training and decision time, case study 6.1.2): " + ", ".join(meta["features"]) + ".",
        "- Excluded: txn_id, txn_ts, city_tier (AI-1) and all customer data (names, mobile numbers). Full card numbers never reach the model.", "",
        "## Performance (test period)", "",
        f"- PR-AUC {m['pr_auc']:.4f} (baseline {meta['metrics']['baseline']['pr_auc']:.4f}); ROC-AUC {m['roc_auc']:.4f}.",
        f"- At 0.70: precision {m['at_step_up_threshold']['precision']:.4f}, recall {m['at_step_up_threshold']['recall']:.4f}.",
        f"- At 0.90: precision {m['at_block_threshold']['precision']:.4f}, recall {m['at_block_threshold']['recall']:.4f}.",
        "- Full tables: `ml/evaluation_report.md`.", "",
        "## Threshold rationale (AI-3)", "",
        "The decision thresholds are configuration (`ai_step_up_threshold` 0.70, `ai_block_threshold` 0.90, from the case study) and can be "
        "changed by a Fraud Risk Manager without a code release. To check them we compare expected cost, where a missed fraud costs its "
        "amount and a false alarm costs INR 150:", "",
        "| Operating point | Threshold | Missed fraud (INR) | False alarms | Total cost (INR) |", "|---|---|---|---|---|",
    ]
    for name, c in meta["costs"].items():
        lines.append(f"| {name} | {c['threshold']} | {c['missed_fraud_inr']:,.2f} | {c['false_alarms']:,} | {c['total_cost_inr']:,.2f} |")
    cost_t = meta["thresholds"]["cost_optimal_validation"]
    lines += ["",
              f"The cost-optimal threshold on the validation slice is **{cost_t:.2f}**. Scores between the step-up and block thresholds lead to "
              "a step-up (ask the customer) rather than a block, which keeps the cost of an uncertain score low for genuine customers. "
              "If the cost-optimal value differs materially from 0.70, the manager can adjust `ai_step_up_threshold` on the Rules page; "
              "the change is versioned and audited.", "",
              "## Segment check (AI-3)", "",
              "| Dimension | Segment | Genuine txns | Model friction | Ratio | System friction | Ratio |", "|---|---|---|---|---|---|---|"]
    for s in meta["segments"]:
        lines.append(f"| {s['dimension']} | {s['segment']} | {s['genuine_txns']:,} | {pct(s['model_friction_rate'])} | {s['model_friction_rate_ratio']:.2f} | "
                     f"{pct(s['system_friction_rate'])} | {s['system_friction_rate_ratio']:.2f} |")
    lines.append("")
    if meta["disparities"]:
        for d in meta["disparities"]:
            lines.append(f"- **{d['dimension']}** ({d['metric']}): ratio {d['ratio']:.2f} is below 0.8; friction is highest for `{d['highest']}`. "
                         "Largest feature differences: " + "; ".join(d["drivers"]) + ".")
        lines += ["",
                  "Likely cause: the higher-friction segment has systematically different transaction patterns (for example, INTL-tier "
                  "transactions are international and far from the home city by definition, and newer cards have little history), so the "
                  "model and rules see more risk signals there. city_tier itself is not a model feature.",
                  "",
                  "Mitigation: monitor the ratio weekly; review the step-up threshold per segment with the cost table above; prefer step-up "
                  "over block (already the policy for uncertain scores); a cardholder travel notice (bonus idea) would suspend geography "
                  "signals for declared trips; feed analysts' FALSE_POSITIVE outcomes (stored in `model_feedback`) into the next training run.", ""]
    else:
        lines += ["All ratios are 0.8 or above, so no segment is disproportionately challenged at the 0.70 threshold.", ""]
    lines += ["## Limitations", "",
              "- Trained on a synthetic, scenario-enriched data pack; real-world performance is unknown.",
              "- Scores are not calibrated probabilities when `scale_pos_weight` > 1; thresholds should be read as score cut-offs.",
              "- Labelled features are pre-computed; live features are computed from stored history with the same definitions, but any "
              "definition drift between the two would reduce accuracy.",
              "- The model does not see merchant identity, only its category and risk level.", "",
              "## Governance", "",
              "- Every decision stores `model_version`, the model features used and the score, so any score can be reproduced.",
              "- Training is one command with a fixed seed: `python ml/train.py`.",
              "- Analysts' outcomes are stored as feedback labels (`model_feedback` table) for the next training run.", ""]
    return "\n".join(lines)


def write_reports(meta, examples, dirs):
    for d in dirs:
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "evaluation_report.md"), "w") as f:
            f.write(evaluation_report(meta, examples))
    with open(os.path.join(dirs[0], "model_card.md"), "w") as f:
        f.write(model_card(meta))
